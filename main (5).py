import os
from glob import glob

lookback = 30  # Window size for sequences (can change)

def create_sequences(df, lookback=30, target_col='Close'):
    features = df.columns.difference(['Date'])  # Use all except Date
    X, y = [], []
    for i in range(lookback, len(df)):
        X.append(df[features].iloc[i-lookback:i].values)
        y.append(df[target_col].iloc[i])
    return np.array(X), np.array(y)

